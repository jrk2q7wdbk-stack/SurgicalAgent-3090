from agent.llm_agent import SurgicalLLMAgent


VIDEO_PATH = "../test.mp4"


def ask(agent, title, question, video_path=None):

    print("\n" + "=" * 70)
    print(title)
    print("=" * 70)

    answer = agent.answer(
        question=question,
        video_path=video_path
    )

    print(answer)


def main():

    agent = SurgicalLLMAgent()

    # ========================================================
    # Q1
    # 首先分析视频
    # ========================================================

    ask(
        agent,
        "Q1：分析视频",
        (
            "请分析这段手术视频，"
            "建立手术事件时间线。"
        ),
        video_path=VIDEO_PATH
    )

    # ========================================================
    # Q2
    # Temporal + Knowledge Graph
    # ========================================================

    ask(
        agent,
        "Q2：20秒 Temporal + KG",
        (
            "20秒时模型识别到了什么操作？"
            "这个器械在 CholecT50 知识图谱中"
            "还能对 gallbladder 执行哪些有效动作？"
            "请明确区分视频识别结果和知识图谱关系。"
        )
    )

    # ========================================================
    # Q3
    # 当前视觉操作 vs KG 中其他可能关系
    # ========================================================

    ask(
        agent,
        "Q3：34秒 Temporal + KG",
        (
            "34秒时模型识别到了什么三元组？"
            "对于这个器械和这个目标，"
            "CholecT50 知识图谱中还有哪些有效动作？"
            "哪些是视频实际识别到的，"
            "哪些只是图谱关系？"
        )
    )

    # ========================================================
    # Q4
    # 跨阶段 + KG
    # ========================================================

    ask(
        agent,
        "Q4：前后操作变化 + KG",
        (
            "视频从前半段到后半段，"
            "明确识别到的器械和操作发生了什么变化？"
            "然后查询知识图谱，"
            "说明这些器械在 CholecT50 中"
            "分别关联哪些动作。"
            "不要把图谱中的动作说成视频实际发生的动作。"
        )
    )

    # ========================================================
    # Q5
    # 反事实/证据边界
    # ========================================================

    ask(
        agent,
        "Q5：KG 不得覆盖视觉证据",
        (
            "如果知识图谱显示 hook 可以和 "
            "cystic_duct 组成 coagulate 和 dissect "
            "两种三元组，"
            "那么视频0到8秒是否可以说"
            "同时发生了 coagulate 和 dissect？"
            "请根据视频时间线和知识图谱分别判断。"
        )
    )


if __name__ == "__main__":
    main()